test_that("correlations", {
  r <- cor_partial_spearman(cohort_sim$NFL_V0, cohort_sim$AGE)
  expect_equal(r$estimate, unname(stats::cor(cohort_sim$NFL_V0, cohort_sim$AGE, method = "spearman")))
  rp <- cor_partial_spearman(cohort_sim$NFL_V0, cohort_sim$MOCA_V0, cohort_sim[, c("AGE", "SEX")])
  expect_true(abs(rp$estimate) <= 1)
  expect_equal(rp$n, nrow(cohort_sim))
  expect_true(is.na(cor_partial_spearman(1:3, 1:3)$estimate))
  expect_error(cor_partial_spearman(1:3, 1:4), "same length")
  cm <- cor_matrix_test(cohort_sim, c(NFL_V0, IL6_V0, MOCA_V0, SEX))
  expect_equal(dim(cm$r), c(3, 3))
  expect_equal(unname(diag(cm$r)), rep(1, 3))
  expect_equal(nrow(cm$long), 3)
  expect_true(isSymmetric(unname(cm$p_adj)))
  expect_error(cor_matrix_test(cohort_sim, AGE), "At least 2")
})

test_that("pca_compute and pca_scores_join", {
  pc <- pca_compute(cohort_sim, c(NFL_V0, IL6_V0, MOCA_V0, AGE), id_col = ID)
  expect_equal(sum(pc$ve), 100)
  expect_equal(pc$n, nrow(cohort_sim))
  expect_true(all(c(".id", "PC1", "PC2") %in% names(pc$scores)))
  pc2 <- pca_compute(cohort_sim, c(NFL_V3, MOCA_V3, AGE), impute = "median")
  expect_equal(pc2$n, nrow(cohort_sim))
  pc3 <- pca_compute(cohort_sim, c(NFL_V3, MOCA_V3, AGE))
  expect_lt(pc3$n, nrow(cohort_sim))
  j <- pca_scores_join(pc, cohort_sim, id_col = ID, n_pc = 3)
  expect_true(all(c("PC1", "PC2", "PC3") %in% names(j)))
  expect_equal(j$ID, cohort_sim$ID)
  expect_error(pca_compute(cohort_sim, AGE), "At least 2")
})
