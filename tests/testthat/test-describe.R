test_that("na_summary and na_complete_cases", {
  s <- na_summary(cohort_sim, list(Bio = c("NFL_V0", "NFL_V3", "NOPE"), Demo = c("AGE", "BMI")))
  expect_equal(nrow(s), 4)
  expect_true(all(diff(s$Pct_missing) <= 0))
  expect_equal(s$N_missing[s$Variable == "NFL_V3"], sum(is.na(cohort_sim$NFL_V3)))
  cc <- na_complete_cases(cohort_sim, list(A = c("AGE", "NFL_V0"), B = c("NFL_V0", "NFL_V3")))
  expect_equal(cc$`N complete`[1], nrow(cohort_sim))
  expect_equal(cc$`N complete`[2], sum(stats::complete.cases(cohort_sim[, c("NFL_V0", "NFL_V3")])))
  expect_error(na_summary(cohort_sim, "x"), "named list")
  expect_error(na_complete_cases(cohort_sim, list("x")), "named list")
})

test_that("score_composite averages oriented z-scores", {
  d <- data.frame(a = c(1, 2, 3), b = c(3, 2, 1))
  out <- score_composite(d, list(dom = c("a", "b")))
  expect_equal(out$COMP_DOM, c(0, 0, 0))
  out2 <- score_composite(d, list(`my dom` = c("a", "b")), direction = c(b = -1))
  expect_equal(out2$COMP_MY_DOM, c(-1, 0, 1))
  d$b[1] <- NA
  expect_true(is.na(score_composite(d, list(x = c("a", "b")), min_prop = 1)$COMP_X[1]))
  expect_error(score_composite(d, list("a")), "named list")
})

test_that("describe_normality gives a verdict", {
  nt <- describe_normality(cohort_sim, c(AGE, CRP_V0, SEX), labels = c(AGE = "Age"))
