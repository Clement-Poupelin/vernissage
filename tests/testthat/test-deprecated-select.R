test_that("deprecated aliases forward to the new functions", {
  withr::local_options(lifecycle_verbosity = "quiet")
  expect_equal(get_label("NFL", c(NFL = "NfL")), "NfL")
  expect_equal(p_to_stars(0.01), "*")
  expect_equal(visit_suffix_map(c("MRI_X0", "AGE_V0")), c(MRI_X0 = "MRI_X_V0"))
  ot <- outliers_table(small(), "x", id_col = "id", rule = "any")
  expect_equal(ot$id, "S20")
  withr::local_options(fairpark.bin_label = "%s (tertiles)")
  expect_equal(unname(expand_labels("BIN_IL6_V0", c(IL6 = "IL-6"))), "IL-6 (tertiles) V0")
  expect_true(is_pw(ggNA(cohort_sim[, 1:8])))
})

