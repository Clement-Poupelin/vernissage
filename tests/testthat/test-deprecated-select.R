})

test_that("column selection accepts strings, variables, bare names and helpers", {
  d <- small()
  sel <- function(vars) vernissage:::.select(rlang::enquo(vars), d, "vars")
  expect_equal(sel(c("x", "y")), c("x", "y"))
  v <- c("x", "y")
  expect_equal(sel(v), c("x", "y"))
  expect_equal(sel(c(x, y)), c("x", "y"))
  expect_equal(sel(x), "x")
  expect_equal(sel(tidyselect::starts_with("x")), "x")
  expect_equal(sel(NULL), NULL)
  expect_message(out <- sel(c("x", "nope")), "not found")
  expect_equal(out, "x")
  expect_error(sel(nope_column), "not found")
  one <- function(col) vernissage:::.select(rlang::enquo(col), d, "col", single = TRUE)
  expect_error(one(c(x, y)), "exactly one")
  expect_error(one("nope"), "not found")
})
